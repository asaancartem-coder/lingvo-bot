# Функция создания клавиатуры
def make_keyboard(options):
    if not options:
        return types.ReplyKeyboardRemove()
    markup = types.ReplyKeyboardMarkup(resize_keyboard=True, one_time_keyboard=True)
    for opt in options:
        markup.add(types.KeyboardButton(opt))
    return markup

